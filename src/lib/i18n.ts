export type Lang = 'en' | 'ms';
const EN: Record<string, string> = {};
let current: Lang = 'en';
let nodes: Element[] = [];

export const lang = () => current;

/** Text for strings that scripts render (not in the markup). */
export function t(key: string): string {
  if (current === 'ms') return MS_DYNAMIC[key] ?? MS[key] ?? EN_DYNAMIC[key] ?? EN[key] ?? key;
  return EN_DYNAMIC[key] ?? EN[key] ?? key;
}

/** Re-scan the page for data-i18n nodes (call after adding marked elements). */
export function scan() {
  nodes = Array.from(document.querySelectorAll('[data-i18n]'));
  for (const el of nodes) {
    const k = el.getAttribute('data-i18n')!;
    if (!(k in EN)) EN[k] = el.innerHTML;
  }
}

export function setLang(next: Lang) {
  current = next;
  const dict = next === 'ms' ? MS : EN;
  for (const el of nodes) {
    const k = el.getAttribute('data-i18n')!;
    if (dict[k] != null) el.innerHTML = dict[k];
  }
  document.documentElement.lang = next;
  document.querySelectorAll('.lang button').forEach((b) =>
    b.setAttribute('aria-pressed', String(b.getAttribute('data-lang') === next)));
  try { localStorage.setItem('seratus-lang', next); } catch {}
  document.dispatchEvent(new CustomEvent('langchange', { detail: next }));
}

export function initLang() {
  scan();
  document.querySelectorAll('.lang button').forEach((b) =>
    b.addEventListener('click', () => setLang(b.getAttribute('data-lang') as Lang)));
  let saved: string | null = null;
  try { saved = localStorage.getItem('seratus-lang'); } catch {}
  if (!saved) saved = /^(ms|id)/i.test(navigator.language || '') ? 'ms' : 'en';
  setLang(saved === 'ms' ? 'ms' : 'en');
}
